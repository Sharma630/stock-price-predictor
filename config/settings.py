SAMPLE_DATA_NOTICE = "Using bundled sample dataset."


def get_index_options_labels() -> Dict[str, str]:
    """Return a mapping of index key -> human readable label for UI selectboxes."""
    return {key: value["label"] for key, value in INDEX_OPTIONS.items()}


def model_paths(index_key: str) -> Dict[str, Path]:
    """Return the standard ticker-specific file paths for a saved model bundle."""
    return {
        "model": TRAINED_MODELS_DIR / f"{index_key}_lstm.keras",
        "scaler": SCALERS_DIR / f"{index_key}_scaler.pkl",
        "metadata": METADATA_DIR / f"{index_key}_metadata.json",
    }
