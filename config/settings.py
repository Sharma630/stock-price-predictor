"""
Central configuration for the Stock Market Index Movement Forecasting project.

Keeping every tunable value in one place makes the rest of the codebase
easier to read and avoids "magic numbers" scattered across modules.
All paths are built with pathlib so the project works unchanged after
being moved to a different computer / drive letter.
"""

from __future__ import annotations

from pathlib import Path
from typing import Dict

# --------------------------------------------------------------------------
# Base paths
# --------------------------------------------------------------------------
BASE_DIR = Path(__file__).resolve().parent.parent

DATA_DIR = BASE_DIR / "data"
RAW_DATA_DIR = DATA_DIR / "raw"
PROCESSED_DATA_DIR = DATA_DIR / "processed"
SAMPLE_DATA_DIR = DATA_DIR / "sample"

MODELS_DIR = BASE_DIR / "models"
TRAINED_MODELS_DIR = MODELS_DIR / "trained"
SCALERS_DIR = MODELS_DIR / "scalers"
METADATA_DIR = MODELS_DIR / "metadata"

for _dir in (
    RAW_DATA_DIR,
    PROCESSED_DATA_DIR,
    SAMPLE_DATA_DIR,
    TRAINED_MODELS_DIR,
    SCALERS_DIR,
    METADATA_DIR,
):
    _dir.mkdir(parents=True, exist_ok=True)

# --------------------------------------------------------------------------
